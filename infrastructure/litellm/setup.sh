#!/bin/bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="/Users/manu/Library/Mobile Documents/com~apple~CloudDocs/Desktop/SERVER-DEV"
VAULT_PATH="$PROJECT_ROOT/infrastructure/msbross-proxy/api_keys_vault.json"
ENV_FILE="$SCRIPT_DIR/.env"

echo "=== LiteLLM Setup ==="

# Generate secure random keys
MASTER_KEY="sk-litellm-master-$(openssl rand -hex 32)"
PROXY_KEY="sk-litellm-proxy-$(openssl rand -hex 32)"

# Extract keys from vault using Python
python3 << 'PYEOF' > "$ENV_FILE"
import json

vault_path = "/Users/manu/Library/Mobile Documents/com~apple~CloudDocs/Desktop/SERVER-DEV/infrastructure/msbross-proxy/api_keys_vault.json"
output_path = "/Users/manu/Library/Mobile Documents/com~apple~CloudDocs/Desktop/SERVER-DEV/infrastructure/litellm/.env"

with open(vault_path) as f:
    vault = json.load(f)

lines = []
lines.append("# LiteLLM Proxy - Auto-generated by setup.sh")
lines.append(f"# Generated at: $(date -u +'%Y-%m-%dT%H:%M:%SZ')")
lines.append("")
lines.append(f"LITELLM_MASTER_KEY={master_key}")
lines.append(f"LITELLM_API_KEY={proxy_key}")
lines.append("")
lines.append("# Provider API Keys (extracted from vault)")
lines.append("")

# Mapping: env var name -> vault path
# Format: provider_name for LLM_PROVIDERS, or root key name
mapping = {
    "OPENAI_API_KEY": ("LLM_PROVIDERS", "OPENAI"),
    "ANTHROPIC_API_KEY": ("LLM_PROVIDERS", "ANTHROPIC"),
    "GOOGLE_API_KEY": ("LLM_PROVIDERS", "GOOGLE_GEMINI"),
    "GROQ_API_KEY": ("LLM_PROVIDERS", "GROQ"),
    "MISTRAL_API_KEY": ("LLM_PROVIDERS", "MISTRAL"),
    "OPENROUTER_API_KEY": ("LLM_PROVIDERS", "OPENROUTER"),
    "DEEPSEEK_API_KEY": ("LLM_PROVIDERS", "DEEPSEEK"),
    "NVIDIA_API_KEY": ("LLM_PROVIDERS", "NVIDIA"),
    "MINIMAX_API_KEY": ("LLM_PROVIDERS", "MINIMAX"),
    "HUGGINGFACE_API_KEY": ("LLM_PROVIDERS", "HUGGINGFACE"),
    "TOGETHER_API_KEY": ("LLM_PROVIDERS", "TOGETHER_AI"),
    "CEREBRAS_API_KEY": ("LLM_PROVIDERS", "CEREBRAS"),
    "SILICONFLOW_API_KEY": ("LLM_PROVIDERS", "SILICONFLOW"),
    "DEEPINFRA_API_KEY": ("LLM_PROVIDERS", "DEEPINFRA"),
    "OPENCODE_ZEN_API_KEY": ("LLM_PROVIDERS", "OPENCODE_ZEN"),
    "XIAOMI_MIMO_API_KEY": ("XIAOMI_MIMO", "API_KEY"),
}

for env_var, (section, key) in mapping.items():
    if section == "LLM_PROVIDERS":
        value = vault.get(section, {}).get(key, [{}])[0].get("key", "")
    else:
        value = vault.get(section, {}).get(key, "")
    
    if not value:
        value = f"# {env_var}=... (not found in vault)"
    
    lines.append(f"{env_var}={value}")

with open(output_path, "w") as f:
    f.write("\n".join(lines) + "\n")
PYEOF

chmod 600 "$ENV_FILE"

echo "✅ LiteLLM .env recreated with real keys from vault"
echo "   Providers loaded: $(grep -c '=[A-Za-z0-9]' "$ENV_FILE" || true)"
echo ""
echo "Next steps:"
echo "   ./quickstart.sh"
echo "   docker compose up -d"
echo "   ./litellm.sh health"
